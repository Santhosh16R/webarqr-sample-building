import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {GLTFLoader} from 'three/examples/jsm/loaders/GLTFLoader.js';
import {Box3,Vector3} from 'three';
import {createTowerAnimation} from '../docs/tower-animation.js';
import {floorScaleFromWidthCm,DEFAULT_WIDTH_CM} from '../docs/model-size.js';
const bytes=await readFile('docs/assets/iNXT_Tower_Construction.glb');
const gltf=await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),'');
const playback=createTowerAnimation(gltf);playback.model.scale.setScalar(floorScaleFromWidthCm(DEFAULT_WIDTH_CM));
const scan=gltf.scene.getObjectByName('Construction_scan');
const halo=gltf.scene.getObjectByName('Floor_scan_halo');
assert.ok(scan&&halo,'Portable scanning rings are missing');
const scanStart=scan.position.y;
const crew=[];gltf.scene.traverse(object=>{if(object.userData.crewRole)crew.push(object);});
assert.equal(crew.filter(o=>o.userData.crewRole==='crane').length,2);
assert.equal(crew.filter(o=>o.userData.crewRole==='robot').length,2);
assert.equal(crew.filter(o=>o.userData.crewRole==='drone').length,3);
const named=name=>{const node=gltf.scene.getObjectByName(name);assert.ok(node,name);return node;};
const snapshot=()=>{
 playback.model.updateMatrixWorld(true);
 return {hook:named('Crane_1_hook').getWorldPosition(new Vector3()),shoulder:named('Robot_1_shoulder').quaternion.clone(),drone:named('Crew_Drone_1').getWorldPosition(new Vector3()),rotor:named('Drone_1_rotor_1').quaternion.clone()};
};
const initial=snapshot();
const heights=[];
const activeCounts=[];
const envelope=new Box3();
for(let frame=0;frame<=480;frame++){
  if(frame)playback.update(1/24);
  playback.model.updateMatrixWorld(true);
  const bounds=new Box3().setFromObject(playback.model);const size=bounds.getSize(new Vector3());
  envelope.union(bounds);
  assert.ok(size.y<=.3+1e-6,`Height cap exceeded at ${frame}`);
  assert.ok(bounds.min.y>=-1e-6,`Equipment sinks below the floor at ${frame}`);
  if(frame%120===0){heights.push(size.y);let count=0;gltf.scene.traverse(o=>{if(o.isMesh&&Math.abs(o.matrixWorld.determinant())>1e-12)count++;});activeCounts.push(count);}
}
playback.update(.01);assert.equal(playback.state.finished,true);
assert.ok(activeCounts.at(-1)>activeCounts[0]+1000);
const end=playback.state.time;playback.update(3);assert.equal(playback.state.time,end);
playback.replay();assert.equal(playback.state.time,0);assert.equal(playback.state.finished,false);
playback.update(5);assert.ok(Math.abs(playback.state.time-5)<1e-6);
const moving=snapshot();
assert.ok(moving.hook.distanceTo(initial.hook)>.02,'Crane hook must lift with progress');
assert.ok(moving.shoulder.angleTo(initial.shoulder)>.1,'Robot shoulder must articulate');
assert.ok(moving.drone.distanceTo(initial.drone)>.02,'Drones must fly during construction');
assert.ok(moving.rotor.angleTo(initial.rotor)>.3,'Drone rotors must spin');
assert.ok(scan.position.y>scanStart+30,'Scan must rise with construction');
assert.ok(scan.scale.x>0&&halo.scale.x>0,'Both blue rings are visible during construction');
playback.update(16);assert.equal(scan.scale.x,0);assert.equal(halo.scale.x,0);
for(let i=1;i<=3;i++)assert.ok(Math.abs(named(`Crew_Drone_${i}`).position.y-.15)<1e-6,'Drones land at completion');
for(let i=1;i<=2;i++)assert.equal(named(`Robot_${i}_welding_light`).scale.x,0,'Welding stops at completion');
playback.replay();assert.ok(scan.scale.x>0&&halo.scale.x>0,'Replay restores the scanner');
assert.ok(snapshot().hook.distanceTo(initial.hook)<1e-8,'Replay resets crane motion');
playback.dispose();
const report={result:'passed',duration:20,clip:gltf.animations[0].name,tracks:gltf.animations[0].tracks.length,crew:{cranes:2,roboticArms:2,drones:3},sceneEnvelopeCm:envelope.getSize(new Vector3()).multiplyScalar(100).toArray(),heightsMetresAt0_5_10_15_20:heights,activeMeshesAt0_5_10_15_20:activeCounts,checks:['24 fps height envelope <= 30 cm','equipment stays above floor','construction progresses','holds completed frame','replay restarts crew motion','blue scan rises during construction','scanner disappears at completion and restores on replay','crane hooks lift','robot shoulders articulate and welding stops','drones fly, rotors spin, and land at completion'],physicalPhonesTested:false};
await writeFile('outputs/tower-animation-checks.json',JSON.stringify(report,null,2));console.log(report);
